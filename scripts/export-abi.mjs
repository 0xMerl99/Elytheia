// Regenerates shared/launchpadAbi.ts from the compiled Uniswap v4 launchpad. Run after changing contracts/src-v4:
//   (cd contracts && FOUNDRY_PROFILE=v4 forge build) && node scripts/export-abi.mjs
import fs from 'node:fs';
import path from 'node:path';

const file = path.join('contracts', 'out-v4', 'V4Launchpad.sol', 'V4Launchpad.json');
const artifact = JSON.parse(fs.readFileSync(file, 'utf8'));
const hook = JSON.parse(fs.readFileSync(path.join('contracts', 'out-v4', 'AntiSnipeHook.sol', 'AntiSnipeHook.json'), 'utf8'));
const out =
  `// AUTO-GENERATED by scripts/export-abi.mjs from contracts/src-v4. Do not edit by hand.\n` +
  `export const launchpadAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n` +
  `export const hookAbi = ${JSON.stringify(hook.abi, null, 2)} as const;\n`;
fs.writeFileSync(path.join('shared', 'launchpadAbi.ts'), out);
console.log(`wrote shared/launchpadAbi.ts (${artifact.abi.length} launchpad + ${hook.abi.length} hook ABI entries)`);
